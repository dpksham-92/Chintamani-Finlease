        var el = {
          amtRange: q('[data-amount-range]'), amtInput: q('[data-amount-input]'),
          amtMinLbl: q('[data-amount-min-label]'), amtMaxLbl: q('[data-amount-max-label]'),
          tenureRange: q('[data-tenure-range]'), tenureOut: q('[data-tenure-out]'), ticks: q('[data-ticks]'),
          rateRange: q('[data-rate-range]'), rateInput: q('[data-rate-input]'),
          emi: q('[data-emi]'), principal: q('[data-principal]'), interest: q('[data-interest]'), total: q('[data-total]')
        };

        var startIdx = tenures.indexOf(num('tenure', tenures[0]));
        var state = {
          amount: clamp(num('amount', amtMin), amtMin, amtMax),
          idx: startIdx < 0 ? 0 : startIdx,
          rate: clamp(num('rate', 12.5), rateMin, rateMax)
        };

        // slider / input limits
        el.amtRange.min = amtMin; el.amtRange.max = amtMax; el.amtRange.step = amtStep;
        el.amtInput.min = amtMin; el.amtInput.max = amtMax;
        el.amtMinLbl.textContent = compact(amtMin);
        el.amtMaxLbl.textContent = compact(amtMax);
        el.tenureRange.min = 0; el.tenureRange.max = tenures.length - 1; el.tenureRange.step = 1;
        el.rateRange.min = rateMin; el.rateRange.max = rateMax; el.rateRange.step = rateStep;
        el.rateInput.min = rateMin; el.rateInput.max = rateMax;

        // tenure ticks (clickable)
        var tickBtns = tenures.map(function (m, i) {
          var b = document.createElement('button');
          b.type = 'button';
          b.textContent = m + 'm';
          b.setAttribute('aria-label', m + ' months');
          b.addEventListener('click', function () { state.idx = i; render(); });
          el.ticks.appendChild(b);
          return b;
        });

        // skip = input jo user abhi type kar raha hai (usko overwrite nahi karna)
        function render(skip) {
          var months = tenures[state.idx];

          el.amtRange.value = state.amount;
          el.amtRange.setAttribute('aria-valuetext', rupee(state.amount));
          if (skip !== 'amount') el.amtInput.value = state.amount;

          el.tenureRange.value = state.idx;
          el.tenureRange.setAttribute('aria-valuetext', months + ' months');
          el.tenureOut.innerHTML = '<strong>' + months + '</strong> <span>Months</span>';
          tickBtns.forEach(function (b, i) {
            var on = i === state.idx;
            b.classList.toggle('is-active', on);
            b.setAttribute('aria-pressed', on ? 'true' : 'false');
          });

          el.rateRange.value = state.rate;
          el.rateRange.setAttribute('aria-valuetext', state.rate + ' percent');
          if (skip !== 'rate') el.rateInput.value = state.rate;

          var r = calculate(state.amount, state.rate, months, method);
          el.emi.textContent = rupee(r.emi);
          el.principal.textContent = rupee(state.amount);
          el.interest.textContent = rupee(r.interest);
          el.total.textContent = rupee(r.total);
        }

        // Loan amount
        el.amtRange.addEventListener('input', function () { state.amount = +this.value; render(); });
        el.amtInput.addEventListener('input', function () {
          var v = parseFloat(this.value);
          if (isFinite(v)) { state.amount = clamp(v, amtMin, amtMax); render('amount'); }
        });
        el.amtInput.addEventListener('change', function () {
          var v = parseFloat(this.value);
          if (isFinite(v)) state.amount = clamp(Math.round(v), amtMin, amtMax);
          render();
        });

        // Tenure
        el.tenureRange.addEventListener('input', function () { state.idx = +this.value; render(); });

        // Interest rate
        el.rateRange.addEventListener('input', function () { state.rate = +this.value; render(); });
        el.rateInput.addEventListener('input', function () {
          var v = parseFloat(this.value);
          if (isFinite(v)) { state.rate = clamp(v, rateMin, rateMax); render('rate'); }
        });
        el.rateInput.addEventListener('change', function () {
          var v = parseFloat(this.value);
          if (isFinite(v)) state.rate = clamp(Math.round(v * 100) / 100, rateMin, rateMax);
          render();
        });

        render();
      }

      document.querySelectorAll('[data-emi-calc]').forEach(init);
    })();
  </script>

